static void draw_splash(Canvas* canvas) {
    canvas_clear(canvas);
    canvas_set_bitmap_mode(canvas, true);
    canvas_draw_icon(canvas, 0, 0, &I_splash_128x64);
    /* ColorXOR sorgt dafür, dass der Text IMMER invertiert zum darunterliegenden
       Pixel gezeichnet wird (auf weißem Bildgrund -> schwarz, auf schwarzem
       Bildgrund -> weiß), unabhängig davon, was gerade im Icon an dieser
       Stelle liegt. So bleibt die Schrift auf jedem Icon-Hintergrund lesbar. */
    canvas_set_color(canvas, ColorXOR);
    canvas_set_font(canvas, FontPrimary);
    canvas_draw_str_aligned(canvas, 64, 56, AlignCenter, AlignBottom, "EAPOL HUNTER");
    canvas_set_font(canvas, FontSecondary);
    canvas_draw_str_aligned(canvas, 64, 63, AlignCenter, AlignBottom, "Druecke OK...");
    canvas_set_color(canvas, ColorBlack);
}

static void draw_menu(Canvas* canvas, AppState* state) {
    canvas_clear(canvas);
    canvas_set_font(canvas, FontPrimary);
    canvas_draw_str(canvas, 2, 10, "EAPOL / PMKID Hunter");
    canvas_draw_line(canvas, 0, 13, 128, 13);

    canvas_set_font(canvas, FontSecondary);

    /* Scroll-Fenster: nur so viele Einträge zeichnen, wie zwischen y=24 und dem
       unteren Bildschirmrand (64px) passen (Zeilenhöhe 9px -> 4 sichtbare
       Zeilen). Das Fenster folgt menu_index, damit die Auswahl immer sichtbar
       bleibt, auch wenn MENU_COUNT mehr Einträge hat als auf den Screen passen. */
    const int row_h = 9;
    const int list_top = 24;
    const int list_bottom = 63;
    const int visible_rows = (list_bottom - list_top) / row_h + 1; /* = 5 bei 24..63 */

    int scroll_offset = 0;
    if(MENU_COUNT > visible_rows) {
        scroll_offset = state->menu_index - (visible_rows - 1);
        if(scroll_offset < 0) scroll_offset = 0;
        int max_offset = MENU_COUNT - visible_rows;
        if(scroll_offset > max_offset) scroll_offset = max_offset;
    }

    for(int row = 0; row < visible_rows; row++) {
        int i = row + scroll_offset;
        if(i >= MENU_COUNT) break;
        int y = list_top + row * row_h;
        if(i == state->menu_index) {
            canvas_draw_box(canvas, 0, y - 8, 124, row_h);
            canvas_set_color(canvas, ColorWhite);
            canvas_draw_str(canvas, 3, y, menu_items[i]);
            canvas_set_color(canvas, ColorBlack);
        } else {
            canvas_draw_str(canvas, 3, y, menu_items[i]);
        }
    }

    /* kleine Scrollbar rechts, wenn nicht alle Einträge passen */
    if(MENU_COUNT > visible_rows) {
        int track_h = list_bottom - list_top + row_h;
        int thumb_h = (track_h * visible_rows) / MENU_COUNT;
        if(thumb_h < 4) thumb_h = 4;
        int thumb_y =
            list_top - 8 + (track_h - thumb_h) * scroll_offset / (MENU_COUNT - visible_rows);
        canvas_draw_line(canvas, 126, list_top - 8, 126, list_bottom + 1);
        canvas_draw_box(canvas, 125, thumb_y, 3, thumb_h);
    }
}

