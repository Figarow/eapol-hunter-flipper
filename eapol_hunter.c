static void render_callback(Canvas* canvas, void* ctx) {
    AppState* state = ctx;
    switch(state->screen) {
    case ScreenSplash:
        draw_splash(canvas);
        break;
    case ScreenMenu:
        draw_menu(canvas, state);
        break;
    case ScreenScanning:
        draw_scanning(canvas, state);
        break;
    case ScreenResult:
        draw_result(canvas, state);
        break;
    case ScreenAbout:
        draw_about(canvas);
        break;
    }
}

static void input_callback(InputEvent* event, void* ctx) {
    AppState* state = ctx;
    furi_message_queue_put(state->input_queue, event, FuriWaitForever);
}

/* ---- Main app entry --------------------------------------------------------- */

int32_t eapol_hunter_app(void* p) {
    UNUSED(p);

    AppState* state = malloc(sizeof(AppState));
    if(!state) {
        FURI_LOG_E(TAG, "malloc AppState failed (%zu bytes)", sizeof(AppState));
        return 1;
    }
    memset(state, 0, sizeof(AppState));
    state->screen = ScreenSplash;
    state->running = true;
    strncpy(state->source_dir, SOURCE_DIR_DEFAULT, sizeof(state->source_dir) - 1);

    state->input_queue = furi_message_queue_alloc(8, sizeof(InputEvent));
    state->view_port = view_port_alloc();
    view_port_draw_callback_set(state->view_port, render_callback, state);
    view_port_input_callback_set(state->view_port, input_callback, state);

    state->gui = furi_record_open(RECORD_GUI);
    gui_add_view_port(state->gui, state->view_port, GuiLayerFullscreen);

    state->notifications = furi_record_open(RECORD_NOTIFICATION);
    notification_message(state->notifications, &sequence_blink_blue_100);

    InputEvent event;
    while(state->running) {
        if(furi_message_queue_get(state->input_queue, &event, 100) == FuriStatusOk) {
            if(event.type == InputTypeShort || event.type == InputTypeRepeat) {
                switch(state->screen) {
                case ScreenSplash:
                    if(event.key == InputKeyOk || event.key == InputKeyBack) {
                        state->screen = ScreenMenu;
                    }
                    break;

                case ScreenMenu:
                    if(event.key == InputKeyUp) {
                        state->menu_index =
                            (state->menu_index - 1 + MENU_COUNT) % MENU_COUNT;
                    } else if(event.key == InputKeyDown) {
                        state->menu_index = (state->menu_index + 1) % MENU_COUNT;
                    } else if(event.key == InputKeyOk) {
                        switch(state->menu_index) {
                        case 0: /* analysieren */
                            state->screen = ScreenScanning;
                            state->scan_running = true;
                            view_port_update(state->view_port);
                            run_analysis(state);
                            state->screen = ScreenResult;
                            notification_message(
                                state->notifications, &sequence_success);
                            break;
                        case 1: /* loeschen */
                            run_delete_unusable(state);
                            state->screen = ScreenResult;
                            notification_message(
                                state->notifications, &sequence_success);
                            break;
                        case 2: /* ergebnis */
                            state->screen = ScreenResult;
                            break;
                        case 3: /* export hinweis */
                            state->screen = ScreenAbout;
                            break;
                        case 4: /* about */
                            state->screen = ScreenAbout;
                            break;
                        case 5: /* beenden */
                            state->running = false;
                            break;
                        }
                    } else if(event.key == InputKeyBack) {
                        state->running = false;
                    }
                    break;

                case ScreenResult:
                case ScreenAbout:
                    if(event.key == InputKeyBack || event.key == InputKeyOk) {
                        state->screen = ScreenMenu;
                    }
                    break;

                case ScreenScanning:
                    /* waehrend Scan blockierend, kein Input verarbeitet */
                    break;
                }
                view_port_update(state->view_port);
            }
        }
    }

    gui_remove_view_port(state->gui, state->view_port);
    furi_record_close(RECORD_GUI);
    furi_record_close(RECORD_NOTIFICATION);
    view_port_free(state->view_port);
    furi_message_queue_free(state->input_queue);
    free(state);

    return 0;
}
