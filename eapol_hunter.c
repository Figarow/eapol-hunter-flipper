/* ---- Byte-pattern EAPOL/PMKID detection ---------------------------------- */

/*
 * Sehr einfache heuristische Erkennung direkt im PCAP-Byte-Stream, ohne vollen
 * 802.11-Parser: Wir suchen nach dem EAPOL EtherType 0x888E, das im
 * Radiotap/802.11-Header nach LLC/SNAP-Encapsulation auftaucht, sowie nach der
 * PMKID-KDE-Signatur (RSN-Key-Data-Tag 0xDD mit OUI 00-0F-AC Type 4) innerhalb
 * von EAPOL-Key-Frames. Das ist bewusst konservativ: false negatives sind ok
 * (dann landet die Datei einfach nicht im Treffer-Ordner), false positives sind
 * durch die Kombination aus EAPOL-Type-Byte + Key-Descriptor extrem unwahrscheinlich.
 */
static bool buffer_has_eapol(const uint8_t* buf, size_t len, bool* has_pmkid) {
    bool found_eapol = false;
    *has_pmkid = false;

    for(size_t i = 0; i + 8 < len; i++) {
        /* EtherType 0x88 0x8E (EAPOL) */
        if(buf[i] == 0x88 && buf[i + 1] == 0x8E) {
            /* Nach dem EtherType folgt EAPOL-Header: version(1) type(1) length(2) */
            size_t p = i + 2;
            if(p + 1 < len) {
                uint8_t eapol_type = buf[p + 1];
                /* Type 3 = EAPOL-Key (das ist der 4-Way-Handshake-Frame-Typ) */
                if(eapol_type == 0x03) {
                    found_eapol = true;
                }
            }
        }
        /* RSN Key Data: Tag 0xDD, dann Length, dann OUI 00:0F:AC Type 4 = PMKID KDE */
        if(buf[i] == 0xDD && i + 6 < len) {
            if(buf[i + 2] == 0x00 && buf[i + 3] == 0x0F && buf[i + 4] == 0xAC &&
               buf[i + 5] == 0x04) {
                *has_pmkid = true;
                found_eapol = true; /* PMKID zaehlt auch als Treffer fuer Hashcat 22000 */
            }
        }
    }
    return found_eapol;
}

static bool scan_file_for_eapol(Storage* storage, const char* path, bool* has_pmkid) {
    File* file = storage_file_alloc(storage);
    bool result = false;
    *has_pmkid = false;

    if(storage_file_open(file, path, FSAM_READ, FSOM_OPEN_EXISTING)) {
        uint8_t buf[READ_CHUNK + 8];
        uint8_t overlap[8] = {0};
        size_t overlap_len = 0;
        bool pmkid_local = false;

        while(true) {
            memcpy(buf, overlap, overlap_len);
            uint16_t read = storage_file_read(file, buf + overlap_len, READ_CHUNK);
            if(read == 0) break;

            size_t total = overlap_len + read;
            bool pmk = false;
            if(buffer_has_eapol(buf, total, &pmk)) {
                result = true;
            }
            if(pmk) pmkid_local = true;

            /* letzte 8 Bytes als Overlap fuer den naechsten Chunk (Pattern koennte
               ueber Chunk-Grenze liegen) */
            overlap_len = total >= 8 ? 8 : total;
            memcpy(overlap, buf + (total - overlap_len), overlap_len);

            if(read < READ_CHUNK) break;
        }
        storage_file_close(file);
        *has_pmkid = pmkid_local;
    }
    storage_file_free(file);
    return result;
}

/* ---- Directory helpers --------------------------------------------------- */

static bool ends_with(const char* s, const char* suffix) {
    size_t ls = strlen(s), lf = strlen(suffix);
    if(lf > ls) return false;
    return strcmp(s + (ls - lf), suffix) == 0;
}

static void build_analyse_dirs(AppState* state, char* filtered_dir, size_t fd_len,
                                char* hash_file, size_t hf_len) {
    char analyse_root[MAX_PATH_LEN + 32];
    snprintf(analyse_root, sizeof(analyse_root), "%s%s", state->source_dir,
             ANALYSE_DIR_SUFFIX);
    snprintf(filtered_dir, fd_len, "%s/%s", analyse_root, FILTERED_SUBDIR);
    snprintf(hash_file, hf_len, "%s/%s", analyse_root, HASH_FILE_NAME);
}

/* Rekursiv über ein Verzeichnis laufen, .pcap-Dateien einsammeln (max MAX_SCAN_FILES) */
static void collect_pcap_files(Storage* storage, const char* dir, AppState* state) {
    File* d = storage_file_alloc(storage);
    if(!storage_dir_open(d, dir)) {
        storage_file_free(d);
        return;
    }

    FileInfo info;
    char name[192];
    while(storage_dir_read(d, &info, name, sizeof(name))) {
        if(state->files_total >= MAX_SCAN_FILES) break;
        char full[MAX_PATH_LEN];
        int n = snprintf(full, sizeof(full), "%s/%s", dir, name);
        if(n < 0 || (size_t)n >= sizeof(full)) continue; /* Pfad zu lang, überspringen */

        if(info.flags & FSF_DIRECTORY) {
            /* nicht in bereits erzeugte Analyse-Ordner rekursieren */
            if(strstr(name, ANALYSE_DIR_SUFFIX) == NULL) {
                collect_pcap_files(storage, full, state);
            }
        } else {
            if(ends_with(name, ".pcap") || ends_with(name, ".pcapng")) {
                strncpy(state->hits[state->files_total].path, full, MAX_PATH_LEN - 1);
                state->hits[state->files_total].size = info.size;
                state->files_total++;
            }
        }
    }
    storage_dir_close(d);
    storage_file_free(d);
}

/* ---- Core: analyze + filter ------------------------------------------------ */

static void run_analysis(AppState* state) {
    Storage* storage = furi_record_open(RECORD_STORAGE);

    state->files_total = 0;
    state->files_scanned = 0;
    state->hits_count = 0;
    state->deleted_count = 0;

    strncpy(state->status_line, "Suche PCAP-Dateien...", sizeof(state->status_line) - 1);

    collect_pcap_files(storage, state->source_dir, state);

    char filtered_dir[MAX_PATH_LEN + 32];
    char hash_file_path[MAX_PATH_LEN + 32];
    build_analyse_dirs(state, filtered_dir, sizeof(filtered_dir), hash_file_path,
                        sizeof(hash_file_path));

    /* Zielordner anlegen (rekursiv, best effort) */
    char analyse_root[MAX_PATH_LEN + 32];
    snprintf(analyse_root, sizeof(analyse_root), "%s%s", state->source_dir,
              ANALYSE_DIR_SUFFIX);
    storage_common_mkdir(storage, analyse_root);
    storage_common_mkdir(storage, filtered_dir);

    File* hash_file = storage_file_alloc(storage);
    storage_file_open(hash_file, hash_file_path, FSAM_WRITE, FSOM_CREATE_ALWAYS);

    for(int i = 0; i < state->files_total; i++) {
        FileHit* hit = &state->hits[i];
        strncpy(state->current_file, hit->path, sizeof(state->current_file) - 1);
        state->files_scanned = i + 1;

        bool has_pmkid = false;
        bool has_eapol = scan_file_for_eapol(storage, hit->path, &has_pmkid);
        hit->has_eapol = has_eapol;
        hit->has_pmkid = has_pmkid;

        if(has_eapol) {
            state->hits_count++;
            /* Datei in gefilterten Ordner kopieren */
            const char* fname = strrchr(hit->path, '/');
            fname = fname ? fname + 1 : hit->path;
            char dest[MAX_PATH_LEN + 32];
            snprintf(dest, sizeof(dest), "%s/%s", filtered_dir, fname);
            storage_common_copy(storage, hit->path, dest);

            /* Hinweiszeile in die Hashdatei (Metadaten-Marker, echte hcxpcapngtool-
               Konvertierung erfolgt am PC — hier Info fuer den Nutzer, welche
               Dateien Kandidaten sind) */
            char line[300];
            int n = snprintf(line, sizeof(line), "# TREFFER: %s (%s)\n", fname,
                              has_pmkid ? "PMKID" : "EAPOL-4Way");
            storage_file_write(hash_file, line, n);
        }

        /* UI alle paar Dateien aktualisieren */
        if(state->view_port) view_port_update(state->view_port);
        furi_delay_ms(2);
    }

    storage_file_close(hash_file);
    storage_file_free(hash_file);

    furi_record_close(RECORD_STORAGE);
    state->scan_done = true;
    state->scan_running = false;
}

static void run_delete_unusable(AppState* state) {
    if(!state->scan_done) return;
    Storage* storage = furi_record_open(RECORD_STORAGE);
    state->deleted_count = 0;
    for(int i = 0; i < state->files_total; i++) {
        if(!state->hits[i].has_eapol) {
            if(storage_common_remove(storage, state->hits[i].path) == FSE_OK) {
                state->deleted_count++;
            }
        }
    }
    furi_record_close(RECORD_STORAGE);
}

