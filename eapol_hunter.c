/*
 * EAPOL Hunter — Flipper Zero App
 * ---------------------------------
 * Durchsucht /ext/... nach Marauder-PCAP-Dateien, erkennt EAPOL-4-Way-Handshakes
 * und PMKID-Frames per einfachem Byte-Pattern-Matching (kein Krypto nötig),
 * kopiert Treffer in einen gefilterten Unterordner und schreibt eine Hashcat-
 * kompatible .22000-Zusammenfassungsdatei (Metadaten-Extraktion, kein Cracking).
 *
 * Das eigentliche Passwort-Cracking (PBKDF2-HMAC-SHA1, 4096 Runden) ist auf der
 * Flipper-CPU (Cortex-M4 @ 64MHz, keine Krypto-Beschleunigung) nicht praktikabel
 * (~1-5 H/s statt ~20000 H/s auf einer PC-CPU) -> letzter Menüpunkt exportiert
 * nur die fertige Hash-Datei zur Weiterverarbeitung mit Hashcat auf dem PC.
 */

